"""Index notices from an extracted WebView2 resource pack against a pinned local installer SBOM."""
import argparse
import json
import re
import shutil
import struct
import subprocess
from pathlib import Path

from base_installer_sbom import file_digest
from lxml import html
from source_sbom import no_links, sha256
from source_vulnerabilities import unique_object

OUTER = 'installer/MicrosoftEdgeWebView2RuntimeInstallerX64.exe'
INNER = 'webview2-mini/MSEDGE.7z'
PACKED = 'webview2-mini/B7/MSEDGE.PACKED.7Z'
MAX_HTML = 32 << 20

# The Windows build environment already uses PowerShell 7. Decode with its .NET
# BrotliStream so the audit does not add a Brotli dependency to the product.
BROTLI = """
$ErrorActionPreference = 'Stop'
$raw = [Console]::OpenStandardInput()
$size = [IO.BinaryReader]::new($raw).ReadInt32()
$reader = [IO.Compression.BrotliStream]::new($raw, [IO.Compression.CompressionMode]::Decompress)
$bytes = [byte[]]::new($size)
$reader.ReadExactly($bytes, 0, $size)
if ($reader.ReadByte() -ne -1) { throw 'Unexpected decoded data' }
[Console]::OpenStandardOutput().Write($bytes, 0, $size)
"""


def bounded_read(path, limit):
    no_links(path.absolute())
    if not path.is_file() or not 0 < path.stat().st_size <= limit:
        raise ValueError('Input size or type outside supported range')
    with path.open('rb') as source:
        data = source.read(limit + 1)
    if len(data) > limit:
        raise ValueError('Input grew while reading')
    return data


def resource_member(pack, resource_id):
    if len(pack) < 16:
        raise ValueError('Truncated resource header')
    version, encoding, count, aliases = struct.unpack_from('<IIII', pack)
    offset = 16 + (count + 1) * 8
    start = offset + aliases * 8
    if version != 5 or encoding not in (0, 1, 2) or count > 100000 or start > len(pack):
        raise ValueError('Unsupported resource table')
    entries = list(struct.iter_unpack('<II', pack[16:offset]))
    if entries[0][1] != start or entries[-1] != (0, len(pack)):
        raise ValueError('Invalid resource boundaries')
    selected = None
    last = 0
    for (identifier, begin), (_, end) in zip(entries, entries[1:]):
        if identifier <= last or begin > end:
            raise ValueError('Invalid resource order')
        if identifier == resource_id:
            selected = pack[begin:end]
        last = identifier
    if selected is None or len(selected) < 9 or selected[:2] != b'\x1e\x9b':
        raise ValueError('Expected a Brotli-compressed credits resource')
    size = int.from_bytes(selected[2:8], 'little')
    if not 0 < size <= MAX_HTML:
        raise ValueError('Credits exceed decoded size limit')
    runtime = shutil.which('pwsh')
    if not runtime:
        raise ValueError('PowerShell 7 with .NET 7 or newer is required')
    decoded = subprocess.run([runtime, '-NoProfile', '-NonInteractive', '-Command', BROTLI],
                             input=struct.pack('<I', size) + selected[8:], capture_output=True, timeout=40, check=True)
    if len(decoded.stdout) != size:
        raise ValueError('Decoded size mismatch')
    return decoded.stdout


def credit_rows(data):
    parser = html.HTMLParser(encoding='utf-8', no_network=True)
    document = html.document_fromstring(data, parser=parser)
    if document.xpath('//title/text()') != ['Credits'] or b'Generated by licenses.py' not in data[:160]:
        raise ValueError('Unexpected credits page')
    rows = []
    for product in document.xpath('//*[@class="product"]'):
        names = product.xpath('./span[@class="title"]')
        sections = product.xpath('./div[@class="license"]/pre')
        if len(names) != 1 or len(sections) != 1 or not names[0].text_content().strip():
            raise ValueError('Missing or ambiguous credits structure')
        name = names[0].text_content().strip()
        body = sections[0].text_content()
        rows.append({'ordinal': len(rows) + 1, 'name': name, 'license_text': body,
                     'text_sha256': sha256(body.encode()), 'text_present': bool(body.strip())})
    if not rows:
        raise ValueError('Empty credits page')
    return rows


def component_digest(component):
    hashes = [h['content'] for h in component['hashes'] if h['alg'] == 'SHA-256']
    if len(hashes) != 1 or not re.fullmatch('[0-9a-f]{64}', hashes[0]):
        raise ValueError('Missing or ambiguous component hash')
    return hashes[0]


def inventory(bom, expected, setup, runtime):
    raw = bounded_read(bom, 32 << 20)
    if sha256(raw) != expected:
        raise ValueError('Installer SBOM digest differs')
    data = json.loads(raw, object_pairs_hook=unique_object)
    root = data['metadata']['component']
    for path, limit in ((setup, 1 << 30), (runtime, 512 << 20)):
        no_links(path.absolute())
        if not path.is_file() or not 0 < path.stat().st_size <= limit:
            raise ValueError('Unexpected installer file')
    setup_sha = file_digest(setup)
    if (data['bomFormat'] != 'CycloneDX' or data['specVersion'] != '1.6' or
            root['bom-ref'] != 'setup:' + setup_sha or component_digest(root) != setup_sha):
        raise ValueError('SBOM does not match setup')
    components = {c['bom-ref']: c for c in data['components']}
    if len(components) != len(data['components']):
        raise ValueError('Duplicate component reference')
    outer = components['file:' + OUTER]
    if outer['type'] != 'file' or outer['name'] != OUTER or component_digest(outer) != file_digest(runtime):
        raise ValueError('Runtime installer differs')
    candidates = [c for c in components.values() if c['type'] == 'application' and
                  c['name'] == 'Microsoft Edge WebView2 Runtime']
    if (len(candidates) != 1 or not re.fullmatch(r'\d+(?:\.\d+){3}', candidates[0]['version'])
            or {'location': OUTER} not in candidates[0]['evidence']['occurrences']):
        raise ValueError('Missing verified runtime version')
    return components, candidates[0]['version'], setup_sha, component_digest(outer)


def member(components, name):
    component = components['file:' + name]
    parents = [row['value'] for row in component['properties'] if row['name'] == 'studyworkbench:container']
    if component['type'] != 'file' or component['name'] != name or len(parents) != 1 or not parents[0].startswith('file:'):
        raise ValueError('Invalid embedded file evidence')
    return component_digest(component), parents[0].removeprefix('file:')


def generate(bom, expected, setup, runtime, pack, resource_id, notices):
    components, version, setup_sha, runtime_sha = inventory(bom, expected, setup, runtime)
    prefix = f'webview2-runtime/Chrome-bin/{version}/'
    pack_sha, parent = member(components, prefix + 'resources.pak')
    nested = member(components, PACKED)[1]
    if (parent != INNER or member(components, INNER)[1] != PACKED or
            not nested.startswith('webview2-updater/') or member(components, nested)[1] != OUTER):
        raise ValueError('Invalid container chain')
    raw = bounded_read(pack, 128 << 20)
    if sha256(raw) != pack_sha:
        raise ValueError('Resource bytes differ from SBOM')
    credits = resource_member(raw, resource_id)
    rows = credit_rows(credits)
    allowed = {prefix + name: INNER for name in (
        'Trust Protection Lists/Mu/LICENSE', 'Trust Protection Lists/Sigma/LICENSE', 'WidevineCdm/LICENSE')}
    allowed['webview2-updater/NOTICE.TXT'] = OUTER
    documents = {}
    for ref, path in notices:
        if ref in documents or ref not in allowed:
            raise ValueError('Unexpected or duplicate notice name')
        data = bounded_read(Path(path), 16 << 20)
        digest, container = member(components, ref)
        if not data.strip() or sha256(data) != digest or container != allowed[ref]:
            raise ValueError('Notice differs from container evidence')
        documents[ref] = {'sha256': digest, 'bytes': len(data)}
    return {'scope': 'local-webview-credits-and-selected-notices', 'redistribution_review_complete': False,
            'sbom_sha256': expected, 'setup_sha256': setup_sha, 'runtime_sha256': runtime_sha,
            'version': version, 'resource_pack_sha256': pack_sha, 'resource_id': resource_id,
            'credits_html_sha256': sha256(credits), 'credits_html_bytes': len(credits), 'entries': rows,
            'selected_notices': documents, 'missing_selected_notices': sorted(set(allowed) - set(documents))}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('bom', 'setup', 'runtime', 'pack', 'output'):
        parser.add_argument('--' + name, type=Path, required=True)
    parser.add_argument('--bom-sha256', required=True, help='Previously verified local nested SBOM SHA-256')
    parser.add_argument('--resource-id', type=int, required=True)
    parser.add_argument('--notice', nargs=2, action='append', default=[], metavar=('SBOM_NAME', 'LOCAL_FILE'))
    args = parser.parse_args()
    no_links(args.output.absolute().parent)
    result = generate(args.bom, args.bom_sha256, args.setup, args.runtime, args.pack, args.resource_id, args.notice)
    with args.output.open('x', encoding='utf-8') as out:
        json.dump(result, out, ensure_ascii=False, indent=2)
        out.write('\n')
    rows = result['entries']
    print(f"Indexed {len(rows)} entries, {sum(not r['text_present'] for r in rows)} with empty text, "
          f"{len(result['selected_notices'])} separate notices verified.")


if __name__ == '__main__':
    main()
